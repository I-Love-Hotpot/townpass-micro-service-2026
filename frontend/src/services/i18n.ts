export function translate(
  locale: Locale,
  label: Label,
  values: Record<string, string | number> = {}
) {
  const template = (locale === 'id' ? id[label] : undefined) ?? zh[label];
  return template.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}
